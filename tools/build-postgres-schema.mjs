// Genera la base estructural; NO traduce procedimientos ni copia datos.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT } from './_env.mjs';

const dir = join(REPO_ROOT, 'db/postgres');
const source = JSON.parse(readFileSync(join(dir, 'source/sqlserver-schema.json'), 'utf8'));
const q = name => '"' + name.replaceAll('"', '""') + '"';
const table = row => `${q(row.SchemaName)}.${q(row.TableName)}`;
function group(rows, key) {
  const groups = new Map();
  for (const row of rows) {
    const k = key(row);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(row);
  }
  return groups;
}
function type(c) {
  switch (c.DataType) {
    case 'int': return 'integer';
    case 'bigint': return 'bigint';
    case 'smallint': return 'smallint';
    case 'bit': return 'boolean';
    case 'date': return 'date';
    case 'datetime2': return `timestamp(${Math.min(c.Scale, 6)}) without time zone`;
    case 'decimal': return `numeric(${c.Precision},${c.Scale})`;
    case 'varbinary': return 'bytea';
    case 'char': return `char(${c.MaxLength})`;
    case 'nvarchar': case 'varchar':
      return c.MaxLength === -1 ? 'text' : `varchar(${c.MaxLength / (c.DataType === 'nvarchar' ? 2 : 1)})`;
    default: throw new Error(`Tipo pendiente: ${c.DataType}`);
  }
}
function expression(sql) {
  // Estas expresiones vienen de metadatos, no de entradas del usuario.
  return sql.replace(/\[([^\]]+)\]/g, (_, name) => q(name)).replace(/\bN'/g, "'");
}
function defaultValue(c) {
  const value = c.DefaultDefinition;
  if (value === '(sysdatetime())') return 'LOCALTIMESTAMP';
  if (value === '(CONVERT([date],sysdatetime()))') return 'CURRENT_DATE';
  if (c.DataType === 'bit' && /^\(\([01]\)\)$/.test(value)) return value.includes('1') ? 'true' : 'false';
  if (/^\(\(-?\d+(\.\d+)?\)\)$/.test(value) || /^\(N?'(?:[^']|'')*'\)$/.test(value)) return expression(value);
  throw new Error(`Default pendiente: ${table(c)}.${c.ColumnName}: ${value}`);
}
const out = [
  '-- Base estructural obtenida de SQLGUTPATATE. PostgreSQL 15+.',
  '-- No incluye datos operativos, vistas, funciones ni procedimientos.',
  '-- Preserva nombres exactos: usar identificadores entre comillas en las consultas.',
  '-- Pendiente paridad de collation y precision temporal (SQL Server: 7, PostgreSQL: 6).',
  ...[...new Set(source.columns.map(c => c.SchemaName))].map(s => `CREATE SCHEMA IF NOT EXISTS ${q(s)};`),
];
for (const [name, columns] of group(source.columns, table)) {
  const definitions = columns.map(c => {
    let def = `${q(c.ColumnName)} ${type(c)}`;
    if (c.ComputedDefinition) {
      if (c.ComputedDefinition !== '(len([Codigo]))') throw new Error(`Calculada pendiente: ${name}`);
      def += ' GENERATED ALWAYS AS (length(rtrim("Codigo"))) STORED';
    } else {
      if (c.IsIdentity) def += ` GENERATED BY DEFAULT AS IDENTITY (START WITH ${c.IdentitySeed} INCREMENT BY ${c.IdentityIncrement})`;
      if (c.DefaultDefinition) def += ` DEFAULT ${defaultValue(c)}`;
    }
    if (!c.Nullable) def += ' NOT NULL';
    return '  ' + def;
  });
  out.push(`\nCREATE TABLE ${name} (\n${definitions.join(',\n')}\n);`);
}
for (const rows of group(source.indexes, r => `${table(r)}.${r.IndexName}`).values()) {
  const i = rows[0];
  if (!['CLUSTERED', 'NONCLUSTERED'].includes(i.IndexType)) throw new Error(`Indice pendiente: ${i.IndexName}`);
  const keys = rows.filter(r => !r.IsIncluded).sort((a,b) => a.KeyOrdinal-b.KeyOrdinal);
  const cols = keys.map(r => q(r.ColumnName)).join(', ');
  if (i.IsPrimaryKey || i.IsUniqueConstraint) {
    out.push(`ALTER TABLE ${table(i)} ADD CONSTRAINT ${q(i.IndexName)} ${i.IsPrimaryKey ? 'PRIMARY KEY' : 'UNIQUE NULLS NOT DISTINCT'} (${cols});`);
  } else {
    const included = rows.filter(r => r.IsIncluded).map(r => q(r.ColumnName));
    out.push(`CREATE ${i.IsUnique ? 'UNIQUE ' : ''}INDEX ${q(i.IndexName)} ON ${table(i)} (${keys.map(r => q(r.ColumnName) + (r.IsDescending ? ' DESC' : '')).join(', ')})${included.length ? ` INCLUDE (${included.join(', ')})` : ''}${i.IsUnique ? ' NULLS NOT DISTINCT' : ''}${i.FilterDefinition ? ` WHERE ${expression(i.FilterDefinition)}` : ''};`);
  }
}
for (const c of source.checks) {
  if (c.IsDisabled || c.IsNotTrusted) throw new Error(`CHECK sin validar en origen: ${c.ConstraintName}`);
  out.push(`ALTER TABLE ${table(c)} ADD CONSTRAINT ${q(c.ConstraintName)} CHECK ${expression(c.Definition)};`);
}
for (const rows of group(source.foreignKeys, r => `${table(r)}.${r.ConstraintName}`).values()) {
  const f = rows[0];
  if (f.IsDisabled || f.IsNotTrusted) throw new Error(`FK sin validar en origen: ${f.ConstraintName}`);
  out.push(`ALTER TABLE ${table(f)} ADD CONSTRAINT ${q(f.ConstraintName)} FOREIGN KEY (${rows.map(r => q(r.ColumnName)).join(', ')}) REFERENCES ${q(f.ReferencedSchema)}.${q(f.ReferencedTable)} (${rows.map(r => q(r.ReferencedColumn)).join(', ')}) ON DELETE ${f.OnDelete.replaceAll('_',' ')} ON UPDATE ${f.OnUpdate.replaceAll('_',' ')};`);
}
writeFileSync(join(dir, '001_schema.sql'), out.join('\n') + '\n');
console.log(`Generado 001_schema.sql: ${group(source.columns, table).size} tablas.`);
